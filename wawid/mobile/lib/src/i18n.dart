// Bilinguisme français / anglais (langue du téléphone par défaut, choix mémorisé).
import 'package:flutter/foundation.dart';
import 'package:shared_preferences/shared_preferences.dart';

final lang = ValueNotifier<String>('fr');

Future<void> initLang() async {
  final prefs = await SharedPreferences.getInstance();
  final saved = prefs.getString('wawid:lang');
  lang.value = saved == 'fr' || saved == 'en' ? saved! : (PlatformDispatcher.instance.locale.languageCode == 'fr' ? 'fr' : 'en');
}

Future<void> setLang(String l) async {
  lang.value = l;
  final prefs = await SharedPreferences.getInstance();
  await prefs.setString('wawid:lang', l);
}

/// Traduction : t('clé'). Les clés absentes en anglais retombent sur le français.
String t(String key, [Map<String, Object> args = const {}]) {
  var s = (lang.value == 'en' ? _en[key] : null) ?? _fr[key] ?? key;
  args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
  return s;
}

